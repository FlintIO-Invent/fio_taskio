// Lab-only build: reuse the installed, pinned Step 4 toolchain; never rebuild it.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const lab = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const id = process.argv[2];
const previews = JSON.parse(await fs.readFile(path.join(lab,'previews.json'),'utf8'));
if (!previews.some(p => p.id === id) || id === 'services-dashboard') throw new Error('Choose a registered new preview; Step 4 is a frozen reference.');
const root = path.join(lab,id);
const tools = path.join(lab,'services-dashboard/daisyui');
const require = createRequire(path.join(tools,'package.json'));
const {build} = require('esbuild');
const dist = path.join(root,'dist');
await fs.mkdir(path.join(dist,'assets'),{recursive:true});
execFileSync(path.join(tools,'node_modules/.bin/tailwindcss'),['-i',path.join(root,'src/input.css'),'-o',path.join(dist,'app.css'),'--minify'],{cwd:tools,stdio:'inherit'});
const result = await build({entryPoints:[path.join(root,'src/app.js')],bundle:true,minify:true,format:'esm',target:['chrome123','firefox128','safari17.5'],outfile:path.join(dist,'app.js'),metafile:true});
await fs.writeFile(path.join(root,'build-meta.json'),JSON.stringify(result.metafile,null,2)+'\n');
await fs.copyFile(path.join(lab,'design-system/tokens.css'),path.join(dist,'tokens.css'));
await fs.copyFile(path.join(lab,'services-dashboard/shared/assets/motionmate-logo.svg'),path.join(dist,'assets/motionmate-logo.svg'));
await fs.copyFile(path.join(lab,'services-dashboard/shared/assets/Feather-MIT.txt'),path.join(dist,'assets/Feather-MIT.txt'));
const fontRoot = path.join(tools,'node_modules/@fontsource-variable/manrope');
await fs.copyFile(path.join(fontRoot,'files/manrope-latin-wght-normal.woff2'),path.join(dist,'assets/manrope-latin-wght-normal.woff2'));
await fs.copyFile(path.join(fontRoot,'LICENSE'),path.join(dist,'assets/Manrope-OFL.txt'));
for (const [pkg,name] of [['daisyui','DaisyUI-MIT.txt'],['tailwindcss','Tailwind-MIT.txt']]) await fs.copyFile(path.join(tools,'node_modules',pkg,'LICENSE'),path.join(dist,'assets',name));
await fs.copyFile(path.join(root,'src/index.html'),path.join(dist,'index.html'));
await fs.copyFile(path.join(lab,'design-system/initial-theme.js'),path.join(dist,'initial-theme.js'));
console.log(`Built ${id}; existing dashboard output preserved.`);
